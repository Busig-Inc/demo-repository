/* Записная книжка Беста: открывается кнопкой "?" в любой сцене и пополняется по ходу игры.
   Всё считается из состояния игрока (state) и сметы движка (ledger), ничего не хранится отдельно.
   Тексты здесь правят сценаристы. Правила: короткие фразы, только факты, термины из словаря. */

const local = (s) => s.plan === 'L' || s.plan === 'H';
const paid = (l, w) => l.free.spent.some((x) => x.work === w);

function goalApparatus(s) {
  if (!s.plan) return 'Запустить новый аппарат и проверить первую партию. Пока в работе.';
  if (s.plan === 'H' || (s.plan === 'L' && s.s9 === 'control')) return 'Аппарат работает, новая партия прошла проверку. Сделано.';
  if (s.plan === 'L') return s.s9 ? 'Аппарат стоит, но новую партию не приняли. Нет денег на повторную проверку.' : 'Аппарат куплен и освоен. Осталось подтвердить партию.';
  if (s.plan === 'N') return 'Аппарат не отправлен, деньги ушли на сборку. Этап сорван.';
  return 'Нового аппарата в этом этапе не будет. Работа идёт по-старому.';
}

function goalResearch(s, l) {
  if (paid(l, 'research')) return 'Исследование Маклеода оплачено, первый опыт начат.';
  if (s.s9 === 'control') return 'Исследование Маклеода перенесено на следующий этап, записи сохранены.';
  if (s.plan && !local(s) && s.plan !== 'W') return 'Исследование Маклеода не начато.';
  if (s.researchPlaced) return 'Исследование Маклеода в календаре, 1 единица отложена на него.';
  return 'С Маклеодом ещё не говорили. Он ждёт в своём кабинете.';
}

function money(s, l) {
  const gift = {
    none: 'Целевые. Вейл ждёт письма на телеграфе.',
    seen: 'Целевые. Вейл готова дать 4 на аппарат, предложение пока не принято.',
    accepted: 'Целевые. 4 от Вейл, только на аппарат.',
    declined: 'Целевые. От дара Вейл отказались.',
  }[s.offers.gift];
  const partner = {
    none: 'Работа партнёра. Клоуз ещё не звонил, позвонить можно из кабинета Connaught.',
    narrow: 'Работа партнёра. Lilly проведёт повторную проверку, взамен данные этапа и метод.',
    broad: 'Работа партнёра. В обмен попало лишнее, список можно сократить.',
    refused: 'Работа партнёра. От обмена с Lilly отказались.',
  }[s.offers.exchange];
  const promised = {
    none: 'Обещанные. Морроу на телеграфе ещё не выслушан.',
    seen: 'Обещанные. Морроу предлагает 8 после приёмки, бумага не взята.',
    taken: 'Обещанные. 8 от покупателя Морроу придут только после приёмки, а 3 нужно отдать сейчас.',
    declined: 'Обещанные. Предложение Морроу не взяли.',
  }[s.offers.morrowN];
  return ['Свободные. ' + l.free.left + ' из 3 от Connaught, можно тратить на что угодно.', gift, partner, promised];
}

function done(s) {
  const out = [];
  if (s.request) out.push(s.request === 'full' ? 'Список для Бантинга собран целиком, с людьми и проверкой.' : 'В списке для Бантинга только аппарат.');
  if (s.hospital) out.push(s.hospital === 'honest' ? 'Врачам ушёл честный ответ, дата будет после совета.' : 'Врачам пообещали больше инсулина без даты.');
  if (s.acts?.['s3.costs']) out.push('Дефриз назвал бюджет: 3 свободные единицы, не хватает 4.');
  if (s.researchPlaced) out.push('Маклеод объяснил свой вопрос, исследование в календаре.');
  if (s.plan) out.push('Совет подписал план.');
  if (s.s8?.cycle) out.push('Первая проверка разошлась, собрана повторная.');
  if (s.s9) out.push('Последняя свободная единица распределена.');
  return out.length ? out : ['Пока ничего. Начните с лаборатории.'];
}

function next(s) {
  if (!s.request) return 'Лаборатория. Узнать у Скотта смету и собрать список для Бантинга.';
  if (!s.hospital) return 'Больница. Ответить врачам, когда будет больше инсулина.';
  if (!s.acts?.['s3.costs']) return 'Кабинет Connaught. Узнать у Дефриза, сколько у вас денег.';
  if (s.offers.gift === 'none' || s.offers.gift === 'seen') return 'Телеграф. Написать Вейл и получить деньги на аппарат.';
  if (s.offers.exchange === 'none') return 'Кабинет Connaught. Позвонить Клоузу в Lilly.';
  if (!s.researchPlaced) return 'Кабинет Маклеода. Выслушать его и решить, из каких денег оплатить опыт.';
  if (!s.plan) return 'Комната заседаний. Выбрать и подписать один план.';
  if (local(s) && !s.s8?.cycle) return 'Сравнить две первые проверки и собрать повторную.';
  if (local(s) && !s.s9) return 'Решить, на что отдать последнюю свободную единицу.';
  return 'Финал и личный разбор.';
}

/* Разделы книжки по порядку. */
export function notebook(s, l) {
  return [
    { h: 'Кто я', lines: ['Чарльз Бест, 23 года. Руковожу выпуском инсулина в Университете Торонто, лето 1922. Готовлю предложения и веду переговоры, обязательства утверждает совет Connaught.'] },
    { h: 'Цели этапа', lines: [goalApparatus(s), goalResearch(s, l)] },
    { h: 'Деньги', lines: money(s, l) },
    { h: 'Что уже сделано', lines: done(s) },
    { h: 'Что дальше', lines: [next(s)] },
  ];
}
